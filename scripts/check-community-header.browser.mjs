/** Comprobaciones de cuenta y novedades con una fixture independiente por navegador. */
export async function checkCommunityHeader(browser, { baseURL, screenshotDir, browserLabel }) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'es-MX' })
  const page = await context.newPage(), admin = await browser.newContext(), results = [], errors = []
  const password = 'Frase ficticia para fotos oficiales 2026'
  const check = (value, label) => { if (!value) throw Error(label); results.push(label) }
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const hero = () => page.getByRole('region', { name: 'Destacados de la comunidad', exact: true })
  const profile = () => page.getByRole('dialog')
  const openProfile = async () => { await page.getByRole('button', { name: /^Abrir mi perfil:/ }).click(); await profile().getByRole('region', { name: 'Opciones de mi cuenta' }).waitFor() }
  const refresh = async () => {
    await openProfile()
    await profile().getByRole('button', { name: 'Actualizar comunidad', exact: true }).click()
    await profile().getByRole('button', { name: 'Actualizar comunidad', exact: true }).waitFor()
    await profile().getByRole('button', { name: 'Cerrar perfil', exact: true }).click()
  }
  const call = async (path, method = 'GET', data, idempotent = false) => {
    const response = await admin.request.fetch(baseURL + '/api/local' + path, { method, data, headers: { Origin: baseURL, ...(idempotent ? { 'Idempotency-Key': crypto.randomUUID() } : {}) } })
    if (!response.ok()) throw Error(`${path}: ${response.status()} ${await response.text()}`)
    return response.json()
  }
  const notice = async (title, audience = 'community') => call('/institutional-posts', 'POST', { title, body: 'Aviso ficticio de comprobación, únicamente en la fixture de QA. El contenido completo se conserva al abrirlo.', kind: 'notice', audience, program: audience === 'group' ? 'Business English' : '', group: audience === 'group' ? 'Mar y jue · 19:30' : '', imageIds: [], showInGallery: false, highlighted: true, expiresAt: null, confirmed: true }, true)
  const withdraw = async title => {
    const post = (await call('/institutional-posts')).posts.find(item => item.title === title)
    await call('/institutional-posts/' + post.id, 'PATCH', { revision: post.revision, confirmed: true, withdraw: true, highlighted: false, expiresAt: post.expiresAt ?? null })
  }
  const settle = () => page.evaluate(() => Promise.all(document.getAnimations().filter(item => item.effect?.getTiming().iterations !== Infinity).map(item => item.finished.catch(() => {}))))
  const shot = async name => { await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' })); await settle(); await page.screenshot({ path: `${screenshotDir}/${browserLabel}-${name}.png` }) }
  const login = async () => {
    await page.goto(baseURL + '/login')
    await page.getByLabel('Correo electrónico', { exact: true }).fill('bob@example.test')
    await page.getByLabel('Contraseña', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Entrar a mi espacio', exact: true }).click()
    await page.getByRole('heading', { name: 'Tu comunidad, al día.', exact: true }).waitFor()
  }
  try {
    await login()
    await call('/auth/login', 'POST', { email: 'admin@example.test', password })
    check(await page.locator('[class*="demoToolbar"]').count() === 0, 'Cabecera conectada elimina las dos franjas de gestión')
    check(!/Demostración para|Prueba local|datos ficticios/.test(await page.locator('body').innerText()), 'Comunidad muestra identidad oficial sin rótulos de demostración')
    check(await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).count() === 0, 'Cerrar sesión deja de ocupar la portada')
    check(await page.getByRole('button', { name: 'Actualizar comunidad', exact: true }).count() === 0, 'Actualizar deja de ocupar la portada')
    check(await page.getByRole('link', { name: 'Mi inscripción', exact: true }).count() === 0, 'Inscripción deja de ocupar la portada')
    check(await page.getByRole('button', { name: 'Mis notificaciones (1)', exact: true }).isVisible(), 'Campana personal accesible junto al avatar')
    check(await page.getByRole('region', { name: 'Avisos fijados por CAI' }).count() === 0, 'Avisos ya no tienen una banda separada')
    check(await hero().getAttribute('data-highlight-kind') === 'notice', 'Aviso fijado aparece primero en el carrusel único')
    check(await hero().getByText('AVISO DE CAI', { exact: true }).isVisible(), 'Aviso queda identificado dentro del carrusel')
    check(await hero().getByRole('button', { name: 'Activar avance automático', exact: true }).isVisible(), 'Aviso inicial queda quieto hasta decisión del usuario')
    check(await hero().getByRole('heading', { name: 'Bienvenidos a nuestro espacio CAI', exact: true }).isVisible(), 'Texto del aviso compartido se conserva')
    await hero().getByRole('button', { name: 'Leer aviso', exact: true }).click()
    await profile().getByRole('region', { name: 'Comentarios publicados' }).waitFor()
    check((await profile().innerText()).includes('Las historias y los comentarios pasan por revisión'), 'Leer aviso abre el contenido completo con su conversación')
    await profile().getByRole('button', { name: 'Cerrar publicación' }).press('Escape')
    await page.getByRole('group', { name: 'Contenido destacado' }).getByRole('button', { name: /^Momentos/ }).click()
    check(await hero().getAttribute('data-highlight-kind') === 'story', 'Momentos lleva a fotografías dentro del mismo carrusel')
    await hero().locator('img').last().waitFor()
    await page.waitForFunction(() => Array.from(document.querySelectorAll('[aria-label="Destacados de la comunidad"] img')).some(image => image.complete && image.naturalWidth > 0))
    check(true, 'Fotografía privada de Momentos carga autorizada')
    const first = await hero().getByRole('heading').innerText()
    await hero().getByRole('button', { name: 'Siguiente destacado' }).click()
    check(await hero().getByRole('heading').innerText() !== first, 'Flechas recorren fotografías y avisos')
    await page.getByRole('group', { name: 'Contenido destacado' }).getByRole('button', { name: /^Avisos de CAI/ }).click()
    check(await hero().getAttribute('data-highlight-kind') === 'notice', 'Acceso directo devuelve al aviso sin perderse entre fotos')
    await page.getByRole('button', { name: 'Mis notificaciones (1)', exact: true }).click()
    check(await profile().getByRole('heading', { name: 'Mis notificaciones', exact: true }).isVisible(), 'Campana abre la bandeja privada independiente')
    await profile().getByRole('button', { name: /^Marcar leído/ }).first().click()
    await profile().getByRole('status').filter({ hasText: 'Mensaje marcado' }).waitFor()
    await profile().getByRole('button', { name: 'Cerrar notificaciones' }).press('Escape')
    check(await page.getByRole('button', { name: 'Mis notificaciones (0)', exact: true }).isVisible(), 'Marcar leído actualiza el contador de la campana')
    check(await hero().getByRole('heading', { name: 'Bienvenidos a nuestro espacio CAI', exact: true }).isVisible(), 'Leer un mensaje privado no altera el aviso de comunidad')
    await openProfile()
    check((await profile().innerText()).includes('Business English · Viernes · 18:00'), 'Programa y grupo están en Mi espacio')
    check(await profile().getByRole('link', { name: 'Mi inscripción', exact: true }).isVisible(), 'Mi inscripción está dentro de Mi cuenta')
    check(await profile().getByRole('button', { name: 'Cerrar sesión', exact: true }).isVisible(), 'Cerrar sesión está dentro de Mi cuenta')
    await profile().getByRole('button', { name: 'Actualizar comunidad', exact: true }).click()
    await profile().getByRole('button', { name: 'Actualizar comunidad', exact: true }).waitFor()
    check(await profile().getByRole('button', { name: 'Cerrar perfil', exact: true }).isVisible(), 'Actualizar funciona sin salir de Mi espacio')
    await profile().getByRole('button', { name: 'Mis notificaciones (0)', exact: true }).click()
    check(await profile().getByRole('heading', { name: 'Mis notificaciones', exact: true }).isVisible(), 'Atajo de perfil abre notificaciones sin apilar ventanas')
    await profile().getByRole('button', { name: 'Cerrar notificaciones' }).press('Escape')
    await openProfile(); await profile().getByRole('link', { name: 'Mi inscripción', exact: true }).click()
    await page.waitForURL('**/mi-inscripcion')
    check(await page.getByRole('dialog').count() === 0, 'Inscripción navega a la ruta existente y cierra el perfil')
    await page.goto(baseURL + '/community'); await hero().waitFor()
    await notice('Aviso nuevo de prueba')
    await notice('Aviso exclusivo de otro grupo', 'group')
    await refresh()
    await page.getByRole('group', { name: 'Contenido destacado' }).getByRole('button', { name: /^Avisos de CAI/ }).click()
    check(await hero().getByRole('heading', { name: 'Aviso nuevo de prueba', exact: true }).isVisible(), 'Aviso nuevo de coordinación se integra tras actualizar')
    check(!(await page.locator('main').innerText()).includes('Aviso exclusivo de otro grupo'), 'Aviso de otro grupo no se filtra al carrusel')
    await withdraw('Aviso nuevo de prueba'); await refresh()
    check(await hero().getByRole('heading', { name: 'Bienvenidos a nuestro espacio CAI', exact: true }).isVisible(), 'Retirar aviso activo muestra un destacado válido')
    for (const theme of ['claro', 'oscuro']) {
      await page.getByRole('button', { name: 'Modo ' + theme, exact: true }).click()
      for (const width of [1440, 768, 375, 320]) {
        await page.setViewportSize({ width, height: 1000 })
        await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
        check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Cabecera y aviso ${theme} ${width}px sin desbordamiento`)
        const controls = await page.locator('header').first().getByRole('button').evaluateAll(buttons => buttons.filter(button => button.getClientRects().length).map(button => { const box = button.getBoundingClientRect(); return { x: box.left, right: box.right } }))
        check(controls.every(control => control.x >= 0 && control.right <= width), `Controles de cabecera ${theme} ${width}px dentro de pantalla`)
        await page.getByRole('group', { name: 'Contenido destacado' }).getByRole('button', { name: /^Avisos de CAI/ }).click()
        if ([1440, 375].includes(width)) await shot(`notice-${theme}-${width}`)
        await page.getByRole('group', { name: 'Contenido destacado' }).getByRole('button', { name: /^Momentos/ }).click()
        check(await hero().getAttribute('data-highlight-kind') === 'story', `Selector de Momentos funciona a ${width}px ${theme}`)
        if ([1440, 375].includes(width)) await shot(`moments-${theme}-${width}`)
      }
    }
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => document.querySelector('button[aria-label*="avance automático"]')?.disabled)
    check(await hero().getByRole('button', { name: /avance automático/ }).isDisabled(), 'Movimiento reducido desactiva la rotación')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.clock.install()
    await hero().getByRole('button', { name: 'Activar avance automático', exact: true }).click()
    await page.getByRole('heading', { name: 'Tu comunidad, al día.', exact: true }).click()
    await page.mouse.move(2, 2)
    const beforeRotation = await hero().getByRole('heading').innerText()
    await page.clock.runFor(8100)
    check(await hero().getByRole('heading').innerText() !== beforeRotation, 'Activar avance automático rota tras ocho segundos')
    await hero().getByRole('button', { name: 'Pausar avance automático', exact: true }).click()
    const paused = await hero().getByRole('heading').innerText()
    await page.clock.runFor(9000)
    check(await hero().getByRole('heading').innerText() === paused, 'Pausa manual mantiene el destacado')
    await withdraw('Bienvenidos a nuestro espacio CAI'); await refresh()
    check(await page.getByRole('group', { name: 'Contenido destacado' }).count() === 0, 'Sin avisos no deja un selector vacío')
    check(await hero().locator('img').count() > 0, 'Sin avisos quedan los momentos fotográficos')
    const emptyFeed = '**/api/local/student/posts', emptyGallery = '**/api/local/student/gallery'
    await page.route(emptyFeed, async route => { const response = await route.fetch(); await route.fulfill({ response, json: { ...(await response.json()), posts: [] } }) })
    await page.route(emptyGallery, async route => { const response = await route.fetch(); await route.fulfill({ response, json: { ...(await response.json()), images: [] } }) })
    await refresh()
    check(await page.getByText('Aquí aparecerán los avisos, las fotografías y las historias que CAI comparta con tu comunidad.', { exact: true }).isVisible(), 'Instalación sin contenido muestra un vacío claro sin controles rotos')
    await page.unroute(emptyFeed); await page.unroute(emptyGallery)
    await openProfile(); await profile().getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
    await page.waitForURL('**/login')
    check((await context.request.get(baseURL + '/api/local/student/me')).status() === 401, 'Cerrar sesión revoca el acceso desde Mi cuenta')
    check(!/Acceso local|Pruebas|ficticia/.test(await page.locator('body').innerText()), 'Acceso también utiliza identidad oficial')
    check(errors.length === 0, 'Sin errores JavaScript ni consola inesperados' + (errors.length ? ': ' + errors.join('; ') : ''))
    return { browser: browserLabel, checks: results.length, results, errors }
  } finally { await context.close(); await admin.close() }
}
