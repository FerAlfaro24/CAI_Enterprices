/** Ejecutar mediante el navegador aislado; pasar credenciales locales como argumentos, nunca guardarlas en este archivo. */
async function checkLocalAccess(page, { baseURL = 'http://127.0.0.1:5173', email, password, browserLabel = 'Prueba' } = {}) {
  const checks = [], matrix = [], errors = []
  const check = (value, message) => { if (!value) throw new Error(message); checks.push(message) }
  const onError = (error) => errors.push(String(error))
  page.on('pageerror', onError)
  const unique = `${Date.now()}${Math.floor(Math.random() * 1000)}`
  const fullName = (minor) => `${minor ? 'Menor' : 'Adulto'} ${browserLabel}${unique}`
  const nav = () => page.getByRole('navigation', { name: 'Administración local', exact: true })
  const register = async (minor) => {
    await page.goto(`${baseURL}/registro-local`)
    const form = page.getByRole('form')
    await form.waitFor({ state: 'visible' })
    check(await form.locator('input[type="password"]').count() === 0, 'La solicitud local no pide contraseña')
    await form.locator('[name="filledBy"][value="alumno"]').check()
    await form.locator('[name="firstName"]').fill(minor ? 'Menor' : 'Adulto')
    await form.locator('[name="lastName"]').fill(`${browserLabel}${unique}`)
    await form.locator('[name="birthDate"]').fill(minor ? '2011-01-01' : '2000-01-01')
    await form.locator('[name="program"]').selectOption({ index: 1 })
    if (await form.locator('[name="group"] option').count() > 1) await form.locator('[name="group"]').selectOption({ index: 1 })
    await form.locator('[name="email"]').fill(`${minor ? 'menor' : 'adulto'}-${browserLabel.toLowerCase()}-${unique}@example.test`)
    await form.getByRole('button', { name: 'Continuar', exact: true }).click()
    if (minor) {
      await form.locator('[name="guardianName"]').fill('Tutor Ficticio')
      await form.locator('[name="relationship"]').selectOption({ index: 1 })
      await form.locator('[name="guardianContact"]').fill('tutor@example.test')
      await form.locator('[name="guardianConsent"]').check()
      await form.getByRole('button', { name: 'Continuar', exact: true }).click()
      check(await form.locator('[name="visibility"][value="comunidad"]').isDisabled(), 'Menor conserva perfil privado')
    }
    await form.getByRole('button', { name: 'Continuar', exact: true }).click()
    await form.locator('[name="acceptRules"]').check()
    await form.locator('[name="acceptPrivacy"]').check()
    const response = page.waitForResponse((r) => r.url().endsWith('/api/local/requests') && r.request().method() === 'POST')
    await form.getByRole('button', { name: 'Enviar solicitud', exact: true }).click()
    check((await response).status() === 201, 'Servidor confirma el guardado de la solicitud')
    await page.getByRole('heading', { name: '¡Solicitud enviada!', exact: true }).waitFor({ state: 'visible' })
    check(await page.getByText(/Se guardó en este equipo/).isVisible(), 'Confirmación distingue guardado y cuenta aún no creada')
  }
  try {
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`${baseURL}/gestion`)
    await page.evaluate(async () => { await fetch('/api/local/auth/logout', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' }) })
    await page.reload()
    await page.getByRole('heading', { name: 'Tu panel de CAI', exact: true }).waitFor({ state: 'visible' })
    check(await page.getByRole('form', { name: 'Acceso a la administración local' }).isVisible(), 'Panel requiere acceso administrativo')
    await register(false)
    await page.goto(`${baseURL}/gestion`)
    await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
    await page.getByLabel('Contraseña', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Entrar al panel', exact: true }).click()
    await page.getByRole('heading', { name: 'Tu trabajo pendiente', exact: true }).waitFor({ state: 'visible' })
    await nav().getByRole('link', { name: 'Solicitudes', exact: true }).click()
    await page.getByRole('button', { name: `Revisar solicitud de ${fullName(false)}`, exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Aprobar solicitud', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await nav().getByRole('link', { name: 'Alumnos', exact: true }).click()
    let row = page.getByRole('listitem').filter({ hasText: fullName(false) })
    await row.getByRole('button', { name: `Suspender a ${fullName(false)}`, exact: true }).click()
    await row.getByText('Suspendido', { exact: true }).waitFor({ state: 'visible' })
    await page.reload()
    row = page.getByRole('listitem').filter({ hasText: fullName(false) })
    await row.getByText('Suspendido', { exact: true }).waitFor({ state: 'visible' })
    check(true, 'Alumno aprobado y suspensión sobreviven a una recarga')
    await row.getByRole('button', { name: `Reactivar a ${fullName(false)}`, exact: true }).click()
    await row.getByText('Activo', { exact: true }).waitFor({ state: 'visible' })
    await register(true)
    await page.goto(`${baseURL}/gestion/solicitudes`)
    await page.getByRole('button', { name: `Revisar solicitud de ${fullName(true)}`, exact: true }).click()
    check(await dialog.getByRole('button', { name: 'Aprobar solicitud', exact: true }).isDisabled(), 'No permite aprobar al menor antes de registrar autorización')
    await dialog.getByLabel('Referencia de la autorización recibida', { exact: true }).fill('Prueba ficticia: autorización confirmada en recepción, folio 123.')
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: 'Registrar autorización', exact: true }).click()
    await dialog.getByText('Autorización del tutor registrada.', { exact: true }).waitFor({ state: 'visible' })
    await dialog.getByRole('button', { name: 'Aprobar solicitud', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.reload()
    await page.getByRole('button', { name: 'Aprobadas', exact: true }).click()
    await page.getByRole('button', { name: `Ver decisión de ${fullName(true)}`, exact: true }).waitFor({ state: 'visible' })
    check(true, 'Autorización y aprobación del menor permanecen guardadas')
    for (const width of [1440, 768, 375, 320]) {
      await page.setViewportSize({ width, height: width > 375 ? 1000 : 812 })
      for (const route of ['/gestion', '/gestion/solicitudes', '/gestion/alumnos', '/registro-local']) {
        await page.goto(`${baseURL}${route}`)
        await page.getByRole('heading', { level: 1 }).waitFor({ state: 'visible' })
        // Esperar al contenido remoto antes de medir evita evaluar solo la pantalla de carga.
        if (route.startsWith('/gestion')) await page.getByRole('navigation', { name: 'Administración local' }).waitFor({ state: 'visible' })
        if (route.startsWith('/gestion')) await page.getByText('Cargando solicitudes y alumnos…', { exact: true }).waitFor({ state: 'hidden' })
        const metrics = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth, headings: document.querySelectorAll('h1').length, main: document.querySelectorAll('main').length }))
        check(!metrics.overflow && metrics.headings === 1 && metrics.main === 1, `${route} a ${width}px: contenido y estructura sin desbordamiento`)
        matrix.push({ route, width, ...metrics })
      }
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`${baseURL}/gestion`)
    await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
    await page.getByRole('heading', { name: 'Tu panel de CAI', exact: true }).waitFor({ state: 'visible' })
    await page.reload()
    await page.getByRole('heading', { name: 'Tu panel de CAI', exact: true }).waitFor({ state: 'visible' })
    check(true, 'Cerrar sesión impide volver al panel recargando')
    check(errors.length === 0, `Sin errores de ejecución: ${errors.join(', ')}`)
    return { status: 'correcto', checks: checks.length, details: checks, matrix, errors }
  } finally { page.off('pageerror', onError) }
}
