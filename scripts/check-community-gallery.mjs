import assert from 'node:assert/strict'
import { createServer } from 'vite'

const server = await createServer({ configFile: false, appType: 'custom', logLevel: 'error', server: { middlewareMode: true, hmr: false, watch: null } })
try {
  const { createInitialState, communityReducer } = await server.ssrLoadModule('/src/features/community/model.ts')
  const { deriveAlbums, selectAlbums, albumCounts, formatAlbumDate } = await server.ssrLoadModule('/src/features/community/gallery/albums.ts')
  let state = createInitialState()
  const original = structuredClone(state.posts)
  let checks = 0
  const check = (value, message) => { assert.ok(value, message); checks += 1 }
  const send = (action) => { state = communityReducer(state, action) }
  const albums = (filter = 'all', sort = 'recent') => selectAlbums(state.posts, filter, sort)

  check(deriveAlbums(state.posts).length === 7, 'Siete publicaciones con medios, incluyendo una pendiente')
  check(albums().length === 6, 'Seis álbumes públicos aprobados, sin añadir álbumes ficticios desconectados')
  assert.deepEqual(albumCounts(albums()), { albums: 6, photos: 9, uniquePhotos: 3 })
  check(albums().every((album) => album.status === 'approved'), 'Ningún pendiente público')
  check(albums().every((album) => { const post = state.posts.find((item) => item.id === album.postId); return album.id === `album:${post.id}` && album.title === post.title && album.description === post.body && album.photos === post.photos && album.cover === post.photos[0] && album.createdAt === post.createdAt && album.author.id === post.authorId }), 'Cada álbum mantiene identidad, contenido, medios, fecha y autor de su publicación')
  check(albums('activities').length === 4 && albums('events').length === 2, 'Filtros de actividades y eventos coherentes')
  check(!albums('achievements').length && !albums('backstage').length, 'Categorías sin fotografías permiten estados vacíos honestos')
  check(albums().every((album, i, list) => !i || Date.parse(list[i - 1].createdAt) >= Date.parse(album.createdAt)), 'Recientes sigue el orden cronológico')
  check(albums('all', 'oldest')[0].postId === 'first-week', 'Primeros recuerdos ordena de antiguo a reciente')
  check(albums('all', 'celebrated')[0].postId === 'weekly-note', 'Más celebrados usa reacciones reales')
  check(albums('all', 'editorial')[0].postId === 'cai-club' && albums('all', 'editorial')[3].postId === 'vale-gallery', 'Selección CAI dispone el destacado y la colección múltiple en espacios editoriales')
  check(formatAlbumDate('2026-10-16T18:40:00-06:00') === 'Hace 1 día · Demo', 'Fechas por día calendario de México: ayer no es hoy aunque pasaron menos de 24 horas')
  check(formatAlbumDate('2026-10-17T19:00:00-06:00') === 'Hoy · Demo', 'Nueva publicación usa el día del escenario')
  assert.deepEqual(state.posts, original)

  send({ type: 'create', id: 'gallery-test', title: 'Galería de prueba', body: 'Una colección ficticia para comprobar el flujo.', category: 'gallery', photoIds: ['books', 'desk'] })
  const pending = deriveAlbums(state.posts).find((album) => album.postId === 'gallery-test')
  check(pending.status === 'pending' && pending.photos.length === 2, 'Creación reutiliza el flujo pendiente y los medios del compositor')
  check(albums().length === 6, 'Crear no publica el álbum')
  send({ type: 'moderate', postId: 'gallery-test', decision: 'approved' })
  check(albums().length === 6, 'Alumno no puede aprobar ni siquiera en la simulación')
  send({ type: 'mode', mode: 'moderator' })
  send({ type: 'moderate', postId: 'gallery-test', decision: 'approved' })
  check(albums().length === 7 && albumCounts(albums()).photos === 11, 'Aprobar añade un álbum y exactamente dos fotos')
  check(albums()[0].postId === 'gallery-test' && albums('activities').some((album) => album.postId === 'gallery-test'), 'Nuevo álbum aparece por fecha y categoría')
  check(new Set(albums().map((album) => album.id)).size === 7, 'Identificadores sin duplicados')
  send({ type: 'react', postId: 'gallery-test', reaction: 'love' })
  check(albums()[0].celebrations === 1, 'Álbum refleja reacciones de la publicación')
  send({ type: 'comment', postId: 'gallery-test', id: 'gallery-comment', body: 'Comentario ficticio de prueba.' })
  check(state.posts.find((post) => post.id === albums()[0].postId).comments.length === 1, 'Vínculo con conversación original se conserva')
  send({ type: 'moderate', postId: 'pending-note', decision: 'rejected' })
  check(deriveAlbums(state.posts).find((album) => album.postId === 'pending-note').status === 'rejected' && !albums().some((album) => album.postId === 'pending-note'), 'Rechazado no aparece en Galería')
  send({ type: 'create', id: 'text-test', title: 'Solo texto', body: 'Esta historia no tiene ninguna fotografía.', category: 'achievement', photoIds: [] })
  send({ type: 'moderate', postId: 'text-test', decision: 'approved' })
  check(albums().length === 7 && !albums('achievements').length, 'Aprobar texto no inventa medios ni álbumes de logros')
  send({ type: 'create', id: 'achievement-test', title: 'Logro ilustrado', body: 'Un logro ficticio con una imagen de muestra.', category: 'achievement', photoIds: ['books'] })
  send({ type: 'moderate', postId: 'achievement-test', decision: 'approved' })
  check(albums('achievements').length === 1, 'El filtro vacío se llena al aprobar una publicación de su categoría con fotos')
  send({ type: 'create', id: 'backstage-test', title: 'Detrás de la práctica', body: 'Una experiencia ficticia sobre la preparación cotidiana.', category: 'experience', photoIds: ['desk'] })
  send({ type: 'moderate', postId: 'backstage-test', decision: 'approved' })
  check(albums('backstage').length === 1, 'Experiencia con medios se clasifica como detrás de cámaras')
  const beforeSelection = structuredClone(state)
  for (const filter of ['all', 'activities', 'achievements', 'events', 'backstage']) for (const sort of ['editorial', 'recent', 'oldest', 'celebrated']) selectAlbums(state.posts, filter, sort)
  assert.deepEqual(state, beforeSelection)
  send({ type: 'reset' })
  assert.deepEqual(state.posts, original)
  check(albums().length === 6 && albumCounts(albums()).photos === 9 && !albums('achievements').length, 'Reinicio restaura los seis álbumes y estados originales')
  console.log(`Galería: ${checks} comprobaciones y 4 comparaciones de igualdad correctas.`)
} finally { await server.close() }
