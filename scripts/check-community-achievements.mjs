import assert from 'node:assert/strict'
import { createServer } from 'vite'

const server = await createServer({ configFile: false, appType: 'custom', logLevel: 'error', server: { middlewareMode: true, hmr: false, watch: null } })
try {
  const { createInitialState, communityReducer } = await server.ssrLoadModule('/src/features/community/model.ts')
  const { selectBadgeGrants, selectPublicRecognitions, selectAchievementStories, validateBadgeRequest } = await server.ssrLoadModule('/src/features/community/achievements/model.ts')
  const { badgeCatalog } = await server.ssrLoadModule('/src/features/community/achievements/catalog.ts')
  const { challenges } = await server.ssrLoadModule('/src/features/community/data/fixtures.ts')
  let state = createInitialState()
  const initial = structuredClone(state)
  const privateText = 'DECLARACION_PRIVADA_SOLO_REVISION: vi una película ficticia y reconocí varias expresiones sin subtítulos.'
  let checks = 0
  const check = (value, message) => { assert.ok(value, message); checks += 1 }
  const send = (action) => { state = communityReducer(state, action) }
  const grants = () => selectBadgeGrants(state)
  const publicOwn = () => selectPublicRecognitions(state).filter((item) => item.grant.memberId === 'alex')
  const request = (id, badgeId = 'movie-explorer', description = privateText) => send({ type: 'requestBadge', id, badgeId, description })
  const role = (mode) => send({ type: 'mode', mode })
  const review = (requestId, decision, reason = 'Decisión explícita y ficticia de CAI para esta prueba.') => send({ type: 'reviewBadge', requestId, decision, reason })
  const unchanged = (action, message) => { const before = state; send(action); check(state === before, message) }

  check(badgeCatalog.filter((badge) => badge.mode === 'automatic').length === 3, 'Las tres definiciones automáticas proceden de Retos')
  check(new Set(badgeCatalog.map((badge) => badge.id)).size === badgeCatalog.length, 'Definiciones con IDs únicos')
  check(!state.badgeRequests.length && !grants().length, 'Alex inicia sin solicitudes ni concesiones inventadas')
  send({ type: 'section', section: 'achievements' })
  check(!grants().length && state.posts.length === initial.posts.length, 'Entrar en Logros no concede ni publica')
  check(selectPublicRecognitions(state).length === 4 && !publicOwn().length, 'Ejemplos públicos existentes separados de progreso personal')
  check(selectPublicRecognitions(state).every((item) => item.post.status === 'approved' && item.post.authorId === item.grant.memberId), 'Reconocimientos históricos vinculados a publicaciones y autores válidos')
  const beforeAutoPosts = state.posts
  send({ type: 'answer', challengeId: 'day-1', answerIndex: 1 })
  check(grants().length === 1 && grants()[0].badgeId === 'first-answer' && state.attempts['day-1'].points === 5, 'Primer error concede participación y primera respuesta, no exige acierto')
  check(state.posts === beforeAutoPosts && !publicOwn().length, 'Insignia automática no publica ni crea reconocimiento público')
  unchanged({ type: 'answer', challengeId: 'day-1', answerIndex: 0 }, 'No hay segundo intento ni concesión duplicada')
  for (const number of [3, 5]) send({ type: 'answer', challengeId: `day-${number}`, answerIndex: challenges[number - 1].correctIndex })
  check(grants().length === 1, 'Días 1,3,5 no conceden tres consecutivos ni cinco días')
  send({ type: 'answer', challengeId: 'day-2', answerIndex: 0 })
  check(grants().some((grant) => grant.badgeId === 'three-consecutive') && grants().length === 2, 'El hueco cubierto produce una serie real de tres')
  send({ type: 'answer', challengeId: 'day-4', answerIndex: 0 })
  check(grants().length === 3 && grants().some((grant) => grant.badgeId === 'five-days'), 'Cinco participaciones desbloquean la tercera, incluso con errores')
  check(state.posts === beforeAutoPosts && !publicOwn().length, 'Completar automáticas no publica ninguna historia')
  send({ type: 'reset' })
  check(!grants().length && !state.badgeRequests.length, 'Reinicio borra también concesiones derivadas')
  check(Boolean(validateBadgeRequest(state, 'movie-explorer', 'corto').description), 'Valida mínimo de descripción')
  check(Boolean(validateBadgeRequest(state, 'movie-explorer', 'x'.repeat(601)).description), 'Valida máximo de descripción')
  check(!validateBadgeRequest(state, 'movie-explorer', privateText).description, 'Descripción corregida deja de producir error')
  for (const badgeId of ['unknown', 'first-answer', 'good-companion']) unchanged({ type: 'requestBadge', id: `invalid-${badgeId}`, badgeId, description: privateText }, 'Rechaza insignia inexistente, automática o institucional no solicitables')
  unchanged({ type: 'requestBadge', id: 'short', badgeId: 'movie-explorer', description: '    ' }, 'No acepta declaración vacía')
  role('moderator')
  unchanged({ type: 'requestBadge', id: 'as-moderator', badgeId: 'movie-explorer', description: privateText }, 'Moderador no solicita como si fuera alumno')
  role('student')
  const originalPosts = state.posts
  request('movie-1')
  check(state.badgeRequests.length === 1 && state.badgeRequests[0].status === 'pending', 'Solicitud nueva comienza pendiente')
  check(!grants().length && state.posts === originalPosts && !publicOwn().length, 'Pendiente no concede, publica ni aparece públicamente')
  unchanged({ type: 'requestBadge', id: 'movie-duplicate', badgeId: 'movie-explorer', description: privateText }, 'Impide segunda pendiente de la misma insignia')
  unchanged({ type: 'reviewBadge', requestId: 'movie-1', decision: 'approved', reason: 'Aprobación que intenta el alumno.' }, 'Alumno no puede aprobar su propia solicitud')
  unchanged({ type: 'reviewBadge', requestId: 'movie-1', decision: 'rejected', reason: 'Rechazo que intenta el alumno.' }, 'Alumno tampoco decide el rechazo')
  unchanged({ type: 'create', id: 'unearned-share', title: 'Intento de compartir', body: 'Mensaje público ficticio de prueba.', category: 'achievement', photoIds: [], badgeId: 'movie-explorer' }, 'No adjunta una insignia pendiente a una publicación')
  role('moderator')
  unchanged({ type: 'reviewBadge', requestId: 'movie-1', decision: 'approved', reason: '' }, 'Decisión debe conservar motivo válido')
  review('movie-1', 'approved')
  check(state.badgeRequests[0].status === 'approved' && state.badgeRequests[0].reviewedBy === 'cai-demo' && state.badgeRequests[0].reviewedAt, 'Decisión explícita conserva revisor y fecha de demo')
  check(grants().length === 1 && grants()[0].source === 'cai' && grants()[0].requestId === 'movie-1', 'Aprobación produce exactamente una concesión personal derivada')
  check(state.posts === originalPosts && !publicOwn().length, 'Aprobar solicitud nunca crea historia pública')
  unchanged({ type: 'reviewBadge', requestId: 'movie-1', decision: 'approved', reason: 'Segundo clic del moderador ficticio.' }, 'Doble aprobación es idempotente')
  unchanged({ type: 'reviewBadge', requestId: 'movie-1', decision: 'rejected', reason: 'No puede sobrescribirse una decisión.' }, 'No sobrescribe una aprobación ya decidida')
  role('student')
  unchanged({ type: 'requestBadge', id: 'movie-again', badgeId: 'movie-explorer', description: privateText }, 'No permite volver a solicitar insignia concedida')
  const share = { type: 'create', id: 'public-story', title: 'Mi película, mi pequeño logro', body: 'Este texto público lo elegí y edité yo. Celebramos un avance ficticio.', category: 'achievement', photoIds: [], badgeId: 'movie-explorer' }
  send(share)
  check(state.posts[0].status === 'pending' && state.posts[0].badgeId === 'movie-explorer', 'Compartir crea publicación pendiente vinculada a concesión')
  check(grants().length === 1 && !publicOwn().length, 'Compartir no duplica concesión ni salta moderación')
  check(!JSON.stringify(state.posts).includes(privateText), 'Descripción privada no se incorpora a publicaciones')
  unchanged({ type: 'moderate', postId: 'public-story', decision: 'approved' }, 'Alumno no aprueba su publicación')
  role('moderator')
  send({ type: 'moderate', postId: 'public-story', decision: 'approved' })
  check(publicOwn().length === 1 && publicOwn()[0].post.id === 'public-story', 'Solo tras moderación aparece reconocimiento voluntario')
  check(!JSON.stringify(selectPublicRecognitions(state)).includes(privateText), 'Ni reconocimiento ni su motivo exponen declaración privada')
  check(grants().length === 1, 'Aprobar publicación no concede de nuevo')
  role('student')
  send({ ...share, id: 'second-story', title: 'Otro mensaje público voluntario' })
  role('moderator')
  send({ type: 'moderate', postId: 'second-story', decision: 'approved' })
  check(publicOwn().length === 1 && publicOwn()[0].post.id === 'second-story', 'Dos historias no duplican reconocimiento de la misma insignia')
  send({ type: 'create', id: 'generic-achievement', title: 'Un logro sin insignia', body: 'Publicación ficticia sin relación con una solicitud.', category: 'achievement', photoIds: [] })
  send({ type: 'moderate', postId: 'generic-achievement', decision: 'approved' })
  check(grants().length === 1 && selectAchievementStories(state.posts).some((post) => post.id === 'generic-achievement'), 'Aprobar logro genérico no concede una insignia')
  const stableState = structuredClone(state)
  selectBadgeGrants(state); selectPublicRecognitions(state); selectAchievementStories(state.posts)
  assert.deepEqual(state, stableState)
  send({ type: 'reset' })
  request('music-rejected', 'music-catcher')
  role('moderator'); review('music-rejected', 'rejected')
  const rejected = state.badgeRequests[0]
  check(rejected.status === 'rejected' && !grants().length && !publicOwn().length, 'Rechazo no concede ni publica')
  role('student')
  unchanged({ ...share, id: 'rejected-share', badgeId: 'music-catcher' }, 'No se comparte una insignia rechazada')
  request('music-retry', 'music-catcher', `${privateText} Añadí otro detalle ficticio.`)
  check(state.badgeRequests.length === 2 && state.badgeRequests[0] === rejected && state.badgeRequests[1].status === 'pending', 'Nueva solicitud tras rechazo conserva el historial anterior')
  unchanged({ type: 'requestBadge', id: 'music-retry-duplicate', badgeId: 'music-catcher', description: privateText }, 'Nuevo intento también impide duplicar pendiente')
  role('moderator'); review('music-retry', 'approved')
  check(grants().length === 1 && grants()[0].requestId === 'music-retry' && state.badgeRequests[0] === rejected, 'Aprobar nuevo intento concede una vez sin alterar rechazo anterior')
  check(!publicOwn().length, 'Aprobar reintento tampoco publica')
  send({ type: 'reset' })
  assert.deepEqual(state.posts, initial.posts)
  assert.deepEqual(state.badgeRequests, [])
  assert.deepEqual(state.attempts, {})
  check(!grants().length && !publicOwn().length && selectPublicRecognitions(state).length === 4, 'Reinicio devuelve solicitudes, concesiones y publicaciones al escenario inicial')
  console.log(`Logros: ${checks} comprobaciones y 4 comparaciones de igualdad correctas.`)
} finally { await server.close() }
