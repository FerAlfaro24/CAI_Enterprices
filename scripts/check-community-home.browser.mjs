/** Ejecutar desde un navegador de automatización aislado contra la fixture de presentación. */
export async function checkCommunityHome(page,{baseURL,screenshotDir,browserLabel='browser',password='Frase ficticia para fotos oficiales 2026'}){
  const checks=[]
  const check=(condition,message)=>{if(!condition)throw Error(message);checks.push(message)}
  const login=async(admin=false)=>{
    await page.context().clearCookies({domain:'127.0.0.1'})
    await page.goto(baseURL+(admin?'/admin':'/login'))
    await page.getByRole('textbox',{name:'Correo electrónico',exact:true}).fill(admin?'admin@example.test':'bob@example.test')
    await page.getByRole('textbox',{name:'Contraseña',exact:true}).fill(password)
    await page.getByRole('button',{name:admin?'Entrar al panel':'Entrar a mi espacio',exact:true}).click()
    await page.getByRole(admin?'link':'heading',{name:admin?'Publicaciones':'Tu comunidad, en imágenes.',exact:true}).waitFor()
  }
  await page.emulateMedia({reducedMotion:'no-preference'})
  await login()
  check((await page.getByRole('note').innerText()).includes('ficticios'),'Demostración identificada')
  const hero=page.getByRole('region',{name:'Destacados de la comunidad',exact:true})
  await hero.locator('img').last().waitFor()
  check(await hero.locator('img').last().evaluate(i=>i.complete&&i.naturalWidth>0),'Fotografía real cargada en Inicio')
  await page.getByRole('button',{name:'Pausar avance automático',exact:true}).click()
  const originalTitle=await hero.getByRole('heading').innerText()
  await page.getByRole('button',{name:'Siguiente destacado',exact:true}).click()
  check(await hero.getByRole('heading').innerText()!==originalTitle,'Carrusel cambia de historia')
  await page.getByRole('button',{name:'Destacado anterior',exact:true}).click()
  const title=await hero.getByRole('heading').innerText()
  await page.getByRole('button',{name:'Ver historia y fotos',exact:true}).click()
  const dialog=page.getByRole('dialog')
  await dialog.getByRole('button',{name:'Conversación (3)',exact:true}).waitFor()
  check((await dialog.innerText()).includes(title),'El destacado abre su historia')
  const before=await dialog.getByRole('button',{name:/^Me encanta:/}).getAttribute('aria-label')
  await dialog.getByRole('button',{name:/^Me encanta:/}).click()
  await dialog.locator('[data-reaction-id="love"][aria-pressed="true"]').waitFor()
  check((await dialog.innerText()).includes('Tu reacción: Me encanta'),'Reacción guardada en la historia')
  await dialog.locator('[data-reaction-id="love"][aria-pressed="true"]').click()
  await page.waitForFunction(()=>!document.querySelector('dialog button[aria-label^="Me encanta:"][aria-pressed="true"]'))
  check(await dialog.getByRole('button',{name:/^Me encanta:/}).getAttribute('aria-label')===before,'Quitar reacción conserva los demás votos')
  await dialog.getByRole('button',{name:'Cerrar publicación',exact:true}).press('Escape')
  check(await page.getByRole('dialog').count()===0,'Escape cierra la historia')
  await page.getByRole('button',{name:'Galería',exact:true}).click()
  await page.getByRole('button',{name:'Álbumes',exact:true}).click()
  await page.getByRole('button',{name:`Explorar álbum: ${title}`,exact:true}).click()
  check((await page.getByRole('dialog').innerText()).includes('Foto 1 de 3'),'Galería agrupa tres fotos en un álbum')
  await page.getByRole('button',{name:'Foto siguiente del álbum',exact:true}).click()
  check((await page.getByRole('dialog').innerText()).includes('Foto 2 de 3'),'Álbum permite recorrer fotos')
  await page.getByRole('button',{name:'Ver historia y conversación',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Conversación (3)',exact:true}).waitFor()
  check((await page.getByRole('dialog').innerText()).includes(title),'Galería llega a la misma conversación')
  await page.getByRole('button',{name:'Cerrar publicación',exact:true}).click()
  await page.getByRole('button',{name:'Inicio',exact:true}).click()
  await page.getByRole('button',{name:'Fotos',exact:true}).click()
  check(await page.locator('[aria-label="Publicaciones de mi grupo"] article').count()===2,'Filtro Fotos muestra los dos álbumes')
  await page.getByRole('button',{name:'Recientes',exact:true}).click()
  check(await page.locator('[aria-label="Publicaciones de mi grupo"] article').count()===6,'Feed muestra seis historias al inicio')
  await page.getByRole('button',{name:/Ver más historias/}).click()
  check(await page.locator('[aria-label="Publicaciones de mi grupo"] article').count()===7,'Paginación muestra las siete historias y el aviso separado')
  for(const theme of ['claro','oscuro']){
    await page.getByRole('button',{name:`Modo ${theme}`,exact:true}).click()
    for(const width of [1440,768,375,320]){
      await page.setViewportSize({width,height:900})
      await page.evaluate(()=>scrollTo(0,0))
      check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Inicio ${width}px ${theme} sin desbordamiento`)
      await page.screenshot({path:`${screenshotDir}/${browserLabel}-home-${width}-${theme}.png`,fullPage:false})
    }
  }
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.waitForFunction(()=>document.querySelector('button[aria-label*="avance automático"]')?.disabled===true)
  check(await page.getByRole('button',{name:/avance automático/}).isDisabled(),'Movimiento reducido desactiva rotación')
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.setViewportSize({width:1440,height:900})
  await login(true)
  await page.getByRole('link',{name:'Publicaciones',exact:true}).click()
  await page.getByText('Crear publicación de CAI',{exact:true}).click()
  const form=page.getByRole('form',{name:'Nueva publicación de coordinación',exact:true})
  check(await form.getByRole('button',{name:'Publicar en la comunidad',exact:true}).isDisabled(),'Publicar requiere revisión explícita')
  await form.getByLabel('¿Qué vas a compartir?',{exact:true}).selectOption('album')
  check(await form.getByRole('checkbox',{name:'Guardar también las fotos en Galería',exact:true}).isChecked(),'Álbum se guarda en Galería automáticamente')
  await form.getByLabel('¿Qué vas a compartir?',{exact:true}).selectOption('notice')
  const noticeTitle=`Aviso de comprobación ${browserLabel}`
  await form.getByLabel('Título de la publicación',{exact:true}).fill(noticeTitle)
  await form.getByLabel('Cuéntale a la comunidad',{exact:true}).fill('Aviso exclusivamente ficticio para verificar el recorrido completo de coordinación.')
  await form.getByRole('checkbox',{name:'Destacar en Inicio',exact:true}).check()
  await form.getByRole('checkbox',{name:'Revisé el contenido, los permisos de las fotos y sus destinatarios',exact:true}).check()
  await form.getByRole('button',{name:'Publicar en la comunidad',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Publicación guardada.'}).waitFor()
  check(true,'Coordinación publica un aviso desde el formulario')
  await login()
  check(await page.getByRole('heading',{name:noticeTitle,exact:true}).count()===1,'El aviso publicado aparece en Inicio')
  await login(true)
  await page.getByRole('link',{name:'Publicaciones',exact:true}).click()
  await page.getByText(/Publicaciones de coordinación \(/).click()
  const record=page.getByRole('listitem').filter({has:page.getByText(noticeTitle,{exact:true})})
  await record.getByRole('button',{name:'Retirar publicación',exact:true}).click()
  await record.getByRole('button',{name:'Confirmar retirada',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Publicación retirada'}).waitFor()
  check(true,'Coordinación retira con confirmación')
  await login()
  check(await page.getByRole('heading',{name:noticeTitle,exact:true}).count()===0,'El aviso retirado desaparece de Inicio')
  return {browser:browserLabel,checks:checks.length,results:checks}
}

