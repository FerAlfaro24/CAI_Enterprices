/** Function input for the existing Brave browser_run_code_unsafe tool; no new dependency. */
async function checkCommunityGallery(page, { baseURL = 'http://127.0.0.1:5173', screenshotDir } = {}) {
  let checks = 0
  const check = (value, message) => { if (!value) throw new Error(message); checks += 1 }
  const gallery = () => page.locator('[aria-label="Álbumes de la comunidad"]')
  const nav = () => page.getByRole('navigation', { name: 'Secciones de comunidad' })
  const filters = () => page.getByRole('group', { name: 'Filtrar álbumes', exact: true })
  const albumTitle = 'Tres rincones, una semana de pequeñas prácticas'
  const albumTrigger = () => gallery().getByRole('button', { name: `Explorar álbum: ${albumTitle}`, exact: true })
  const albumDialog = () => page.getByRole('dialog', { name: albumTitle, exact: true })
  const snap = async (name, locator) => {
    if (!screenshotDir) return
    await page.evaluate(() => document.fonts.ready)
    if (!locator) await page.evaluate(() => scrollTo({ top: 0, behavior: 'instant' }))
    await page.mouse.move(2, 2)
    await page.waitForTimeout(100)
    if (locator) await locator.screenshot({ path: `${screenshotDir}/${name}.png` })
    else await page.screenshot({ path: `${screenshotDir}/${name}.png`, fullPage: true })
  }
  const demoOpen = async () => {
    const details = page.locator('#community-demo-controls')
    if (await details.getAttribute('open') === null) await details.locator('summary').click()
  }
  const demoClose = async () => {
    const details = page.locator('#community-demo-controls')
    if (await details.getAttribute('open') !== null) await details.locator('summary').click()
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto(`${baseURL}/community`)
  await nav().getByRole('button', { name: 'Galería', exact: true }).click()
  await page.getByRole('button', { name: 'Modo claro', exact: true }).click()
  check(await page.getByRole('heading', { level: 1, name: 'Así se vive CAI' }).count() === 1, 'Encabezado aprobado de Galería')
  check(await gallery().getByRole('article').count() === 6, 'Seis álbumes iniciales')
  check(await page.getByRole('status').filter({ hasText: '6 álbumes · 9 fotos' }).count() === 1, 'Conteos reales y anunciados de resultados')
  check(await filters().getByRole('button').count() === 5 && await filters().getByRole('button', { name: 'Todas las fotos', exact: true }).getAttribute('aria-pressed') === 'true', 'Cinco filtros accesibles y todas seleccionadas')
  await page.getByRole('button', { name: 'Explorar álbum', exact: true }).click()
  const featured = page.getByRole('dialog', { name: 'Así imaginamos nuestro café de conversación', exact: true })
  check(await featured.count() === 1 && (await featured.innerText()).includes('Foto 1 de 1'), 'Explorar destacado abre su álbum real')
  check(await featured.getByRole('button', { name: 'Foto siguiente del álbum', exact: true }).isDisabled(), 'Álbum de una foto no promete navegación inexistente')
  await page.keyboard.press('Escape')
  check(await page.getByRole('button', { name: 'Explorar álbum', exact: true }).evaluate((el) => el === document.activeElement), 'Escape restaura foco al CTA destacado')
  await filters().getByRole('button', { name: 'Actividades', exact: true }).click()
  check(await gallery().getByRole('article').count() === 4, 'Actividades filtra cuatro álbumes')
  await snap('08-filtro-actividades')
  await filters().getByRole('button', { name: 'Eventos', exact: true }).click()
  check(await gallery().getByRole('article').count() === 2, 'Eventos filtra dos álbumes')
  await snap('09-filtro-eventos')
  for (const category of ['Logros', 'Detrás de cámaras']) {
    await filters().getByRole('button', { name: category, exact: true }).click()
    check(await page.getByRole('heading', { name: 'Aquí todavía hay momentos por guardar.', exact: true }).count() === 1, `${category} muestra estado vacío sin inventar álbumes`)
  }
  await snap('10-estado-vacio')
  await page.getByRole('button', { name: 'Ver todas las fotos', exact: true }).click()
  check(await gallery().getByRole('article').count() === 6, 'Volver a todas restaura el mosaico')
  await page.getByLabel('Orden de álbumes', { exact: true }).selectOption('recent')
  check((await gallery().getByRole('article').first().getAttribute('aria-label')).includes('Mi plan de viernes'), 'Orden recientes sigue las fechas')
  await page.getByLabel('Orden de álbumes', { exact: true }).selectOption('editorial')
  check((await gallery().getByRole('article').first().getAttribute('aria-label')).includes('café de conversación'), 'Selección CAI restaura el orden editorial')
  await albumTrigger().click()
  check(await albumDialog().getByRole('button', { name: 'Cerrar álbum', exact: true }).evaluate((el) => el === document.activeElement), 'Diálogo enfoca el cierre')
  check(await albumDialog().getAttribute('aria-describedby') !== null && (await albumDialog().innerText()).includes('no representan alumnos'), 'Diálogo tiene descripción de privacidad')
  check(await page.evaluate(() => document.body.style.overflow === 'hidden'), 'Diálogo bloquea scroll de fondo')
  await snap('11-detalle-album', albumDialog())
  await albumDialog().getByRole('button', { name: 'Foto siguiente del álbum', exact: true }).click()
  check(await albumDialog().getByRole('status').innerText() === 'Foto 2 de 3', 'Siguiente muestra segunda foto y anuncia posición')
  check((await albumDialog().locator('figcaption').innerText()).includes('Janko'), 'La procedencia cambia con la foto')
  await snap('12-segunda-fotografia', albumDialog())
  await albumDialog().getByRole('group', { name: 'Fotografías del álbum', exact: true }).press('ArrowRight')
  check(await albumDialog().getByRole('status').innerText() === 'Foto 3 de 3', 'Teclado navega a la tercera')
  await albumDialog().getByRole('button', { name: /^Ver foto 1:/ }).click()
  check(await albumDialog().getByRole('status').innerText() === 'Foto 1 de 3', 'Miniatura permite elegir foto')
  await albumDialog().getByRole('button', { name: 'Foto anterior del álbum', exact: true }).click()
  check(await albumDialog().getByRole('status').innerText() === 'Foto 3 de 3', 'Navegación circular vuelve a la última')
  await albumDialog().getByRole('button').last().focus()
  await page.keyboard.press('Tab')
  check(await albumDialog().getByRole('button', { name: 'Cerrar álbum', exact: true }).evaluate((el) => el === document.activeElement), 'Tab mantiene foco dentro del diálogo')
  await page.keyboard.press('Shift+Tab')
  check(await albumDialog().getByRole('button').last().evaluate((el) => el === document.activeElement), 'Shift+Tab vuelve al último control')
  await albumDialog().getByRole('button', { name: 'Ver publicación y conversación', exact: true }).click()
  const story = page.getByRole('dialog', { name: 'La historia completa', exact: true })
  check(await story.count() === 1 && await story.getByRole('textbox').count() === 1, 'Publicación asociada conserva comentarios abiertos')
  await story.getByRole('button', { name: /^Me encanta:/ }).click()
  check(await story.getByRole('button', { name: /^Me encanta:/ }).getAttribute('aria-pressed') === 'true', 'Reacciones originales funcionales')
  await story.getByRole('textbox').fill('Un comentario ficticio desde la galería.')
  await story.getByRole('button', { name: 'Comentar', exact: true }).click()
  check(await story.getByText('Un comentario ficticio desde la galería.', { exact: true }).count() === 1, 'Comentario aparece en la publicación original')
  await page.keyboard.press('Escape')
  check(await albumDialog().getByRole('button', { name: 'Ver publicación y conversación', exact: true }).evaluate((el) => el === document.activeElement), 'Cerrar historia restaura foco en el álbum')
  await page.keyboard.press('Escape')
  check(await albumTrigger().evaluate((el) => el === document.activeElement) && await page.evaluate(() => document.body.style.overflow !== 'hidden'), 'Cerrar álbum devuelve foco y desbloquea fondo')
  await page.getByRole('button', { name: 'Compartir foto', exact: true }).click()
  const composer = page.getByRole('dialog', { name: 'Comparte un pequeño paso', exact: true })
  check(await composer.getByLabel('Categoría', { exact: true }).inputValue() === 'gallery', 'Compositor existente empieza en Galería')
  await composer.getByLabel('Título', { exact: true }).fill('Álbum de revisión ficticio')
  await composer.getByLabel('Tu historia de muestra', { exact: true }).fill('Dos imágenes de stock para demostrar la aprobación de una publicación de muestra.')
  await composer.getByRole('checkbox').nth(0).check()
  await composer.getByRole('checkbox').nth(1).check()
  await composer.getByRole('button', { name: 'Enviar a revisión', exact: true }).click()
  check(await gallery().getByRole('article').count() === 6 && await page.getByRole('region', { name: 'Estado de tus publicaciones demo', exact: true }).getByText('Pendiente', { exact: true }).count() === 1, 'Publicación pendiente no es álbum público')
  await snap('13-publicacion-pendiente')
  await demoOpen()
  await page.getByLabel('Vista demo', { exact: true }).selectOption('moderator')
  await demoClose()
  const review = page.getByRole('article', { name: 'Revisar Álbum de revisión ficticio', exact: true })
  check(await review.getByRole('img').count() === 2, 'Moderación conserva los dos medios enviados')
  await review.getByRole('button', { name: 'Aprobar', exact: true }).click()
  await page.getByLabel('Orden de álbumes', { exact: true }).selectOption('recent')
  check(await gallery().getByRole('article').count() === 7 && (await gallery().getByRole('article').first().getAttribute('aria-label')) === 'Álbum de revisión ficticio', 'Aprobar crea un álbum derivado visible y ordenado')
  check(await page.getByRole('status').filter({ hasText: '7 álbumes · 11 fotos' }).count() === 1, 'Conteos aumentan exactamente un álbum y dos fotos')
  await snap('14-album-aprobado')
  await gallery().getByRole('button', { name: 'Explorar álbum: Álbum de revisión ficticio', exact: true }).click()
  const created = page.getByRole('dialog', { name: 'Álbum de revisión ficticio', exact: true })
  check(await created.getByRole('status').innerText() === 'Foto 1 de 2', 'Nuevo álbum contiene los dos medios aprobados')
  await snap('15-detalle-album-aprobado', created)
  await page.keyboard.press('Escape')
  await page.getByRole('article', { name: 'Revisar Una nueva frase para mi rincón de práctica', exact: true }).getByRole('button', { name: 'Rechazar', exact: true }).click()
  check(await gallery().getByRole('article').count() === 7, 'Rechazar otra publicación no la añade al mosaico')
  await demoOpen()
  await page.getByRole('button', { name: 'Reiniciar demo', exact: true }).click()
  await demoClose()
  await nav().getByRole('button', { name: 'Galería', exact: true }).click()
  check(await gallery().getByRole('article').count() === 6 && await page.getByRole('region', { name: 'Estado de tus publicaciones demo', exact: true }).count() === 0, 'Reinicio restaura seis álbumes, sin envíos propios')
  await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
  check(await page.locator('[data-theme]').getAttribute('data-theme') === 'dark', 'Tema oscuro respeta el selector existente')
  await nav().getByRole('button', { name: 'Inicio', exact: true }).click()
  await nav().getByRole('button', { name: 'Galería', exact: true }).click()
  check(await page.locator('[data-theme]').getAttribute('data-theme') === 'dark' && await gallery().getByRole('article').count() === 6, 'Tema y datos conservados al navegar')
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordamiento horizontal')
  return { checks, status: 'correcto' }
}
