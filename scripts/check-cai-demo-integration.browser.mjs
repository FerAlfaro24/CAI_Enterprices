/** Supply to the existing isolated Brave / Opera GX browser_run_code_unsafe tool.
 * Build + preview on 4180. No extra dependencies. Screenshots are optional.
 */
async function checkCaiDemoIntegration(page, { baseURL = 'http://127.0.0.1:4180', screenshotDir } = {}) {
  const details = [], matrix = [], errors = [], warnings = [], requests = []
  const check = (value, message) => { if (!value) throw new Error(message); details.push(message) }
  const onError = (error) => errors.push(String(error))
  const onConsole = (message) => { if (message.type() === 'error') errors.push(message.text()); if (message.type() === 'warning') warnings.push(message.text()) }
  const onRequest = (request) => requests.push({ method: request.method(), url: request.url(), body: request.postData() })
  const snap = async (name) => { if (screenshotDir) { await page.mouse.move(1, 1); await page.screenshot({ path: `${screenshotDir}/${name}.png`, animations: 'disabled' }) } }
  const link = (href) => page.locator(`a[href="${href}"]:visible`).first()
  const landingLogin = async () => {
    const access = page.getByRole('link', { name: 'Iniciar sesión / Registrarse', exact: true }).filter({ visible: true }).first()
    if (!(await access.isVisible())) await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
    await access.click()
  }
  const communityNav = () => page.getByRole('navigation', { name: 'Secciones de comunidad' })
  const quiz = () => page.getByRole('region', { name: 'Reto del día compartido', exact: true })
  const adminNav = () => page.getByRole('navigation', { name: 'Secciones de administración' })
  const adminGo = async (href) => { if (await page.getByRole('button', { name: 'Abrir menú', exact: true }).isVisible()) await page.getByRole('button', { name: 'Abrir menú', exact: true }).click(); await adminNav().locator(`a[href="${href}"]`).click() }
  const storage = () => page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))
  page.on('pageerror', onError); page.on('console', onConsole); page.on('request', onRequest)
  try {
    await page.bringToFront(); await page.emulateMedia({ reducedMotion: 'reduce' }); await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(baseURL); await page.evaluate(() => document.fonts.ready); await snap('01-landing-1440')
    await landingLogin()
    check(new URL(page.url()).pathname === '/login', 'Landing → Login mediante acceso visible')
    await snap('02-login-1440')
    await page.getByRole('button', { name: 'Entrar a la comunidad demo', exact: true }).click()
    check(new URL(page.url()).pathname === '/login' && await page.locator('#login-email').evaluate((el) => !el.validity.valid), 'Formulario vacío conserva validación nativa')
    await page.getByLabel('Correo electrónico', { exact: true }).fill('integracion@example.test')
    await page.getByLabel('Contraseña de muestra', { exact: true }).fill('SOLO-DEMO-642')
    await page.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
    check(await page.locator('#login-password').getAttribute('type') === 'text', 'Mostrar contraseña funciona')
    await page.getByRole('button', { name: 'Ocultar contraseña', exact: true }).click()
    check(await page.locator('#login-password').getAttribute('type') === 'password', 'Ocultar contraseña funciona')
    const beforeStorage = await storage()
    await page.getByRole('button', { name: 'Entrar a la comunidad demo', exact: true }).click()
    check(new URL(page.url()).pathname === '/community', 'Login visual → Comunidad sin servidor')
    check(!JSON.stringify(await storage()).includes('SOLO-DEMO-642') && !JSON.stringify(await storage()).includes('integracion@example.test'), 'Login no persiste correo ni contraseña')
    await page.getByRole('button', { name: 'Modo oscuro', exact: true }).click()
    await page.setViewportSize({ width: 375, height: 812 }); await snap('06-community-375-oscuro')
    await communityNav().getByRole('button', { name: 'Retos', exact: true }).click()
    await page.waitForFunction(() => document.activeElement?.id === 'community-title')
    await quiz().getByRole('radio').first().check(); await quiz().getByRole('button', { name: '¡Comprobar!', exact: true }).click()
    check((await quiz().getByRole('status').innerText()).includes('+15 puntos ficticios'), 'Reto conserva concesión +15')
    await page.locator('#community-demo-controls summary').click(); await link('/admin').click()
    check(new URL(page.url()).pathname === '/admin', 'Comunidad → Administración sin recarga')
    check(await page.getByText(/Demo independiente: publicaciones y ajustes/).isVisible(), 'Panel distingue sus escenarios independientes')
    if (await page.getByRole('button', { name: 'Abrir menú', exact: true }).isVisible()) await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
    await link('/community').click()
    check((await quiz().getByRole('status').innerText()).includes('+15 puntos ficticios'), 'Salir y regresar conserva resultado y sección de Retos')
    await communityNav().getByRole('button', { name: 'Logros', exact: true }).click()
    check(await page.getByRole('region', { name: 'Insignias conseguidas de Alex', exact: true }).getByRole('article').count() === 1, 'Salir y regresar conserva la insignia derivada')
    check(await page.locator('[data-theme]').getAttribute('data-theme') === 'dark', 'Tema oscuro conservado entre áreas')
    await link('/').click()
    await landingLogin(); await page.getByRole('button', { name: /^Demo administrador/ }).click()
    check(new URL(page.url()).pathname === '/admin', 'Login demo → Administración sin campos obligatorios')
    await adminGo('/admin/publicaciones')
    await page.getByRole('button', { name: /^Revisar / }).first().click()
    const postDialog = page.getByRole('dialog')
    await postDialog.getByRole('button', { name: 'Rechazar', exact: true }).click()
    check(await postDialog.getByRole('alert').isVisible(), 'Moderación exige motivo de rechazo')
    await postDialog.getByRole('radio').first().check(); await postDialog.getByRole('button', { name: 'Rechazar', exact: true }).click()
    check(await page.getByRole('dialog').count() === 0, 'Rechazo con motivo cierra revisión')
    await page.getByRole('button', { name: /^Rechazadas/ }).click(); await page.getByRole('button', { name: /^Revisar / }).first().click()
    await page.getByRole('dialog').getByRole('button', { name: 'Devolver a revisión', exact: true }).click()
    check(await page.getByRole('dialog').count() === 0, 'Deshacer moderación sigue operativo')
    await page.getByRole('button', { name: /^En revisión/ }).click()
    await page.getByRole('article').filter({ hasText: 'Requiere verificación' }).first().getByRole('button', { name: /^Revisar / }).click()
    const review = page.getByRole('dialog'), reviewedTitle = await review.getByRole('heading').innerText()
    if (await review.getByRole('checkbox').count()) {
      check(await review.getByRole('button', { name: 'Publicar', exact: true }).isDisabled(), 'Publicación marcada exige verificación explícita')
      await review.getByRole('checkbox').check()
    }
    await review.getByRole('button', { name: 'Publicar', exact: true }).click()
    await page.getByRole('button', { name: /^Publicadas/ }).click()
    check(await page.getByRole('heading', { name: reviewedTitle, exact: true }).count() === 1, 'Publicar mueve la historia a la cola publicada del panel')
    await page.setViewportSize({ width: 1440, height: 1000 }); await adminGo('/admin'); await snap('05-admin-1440')
    await link('/').click(); await link('/registro').click()
    check(new URL(page.url()).pathname === '/registro', 'Landing → Registro existente')
    await page.setViewportSize({ width: 768, height: 1000 }); await snap('04-registro-768')
    const register = async (minor) => {
      const form = page.getByRole('form')
      await form.getByRole('button', { name: 'Continuar', exact: true }).click()
      check(await form.getByRole('alert').count() === 1, 'Registro valida campos antes de avanzar')
      await form.locator('input[name="filledBy"][value="alumno"]').check()
      await form.locator('[name="firstName"]').fill(minor ? 'Menor' : 'Integracion')
      await form.locator('[name="lastName"]').fill('Prueba')
      await form.locator('[name="birthDate"]').fill(minor ? '2011-01-01' : '2000-01-01')
      await form.locator('[name="program"]').selectOption({ index: 1 })
      const groups = await form.locator('[name="group"] option').count(); if (groups > 1) await form.locator('[name="group"]').selectOption({ index: 1 })
      await form.locator('[name="email"]').fill(minor ? 'menor@example.test' : 'adulto@example.test')
      await form.locator('[name="password"]').fill('RegistroDemo642'); await form.locator('[name="confirm"]').fill('RegistroDemo642')
      await form.getByRole('button', { name: 'Continuar', exact: true }).click()
      if (minor) {
        await form.locator('[name="guardianName"]').fill('Tutor Prueba'); await form.locator('[name="relationship"]').selectOption({ index: 1 })
        await form.locator('[name="guardianContact"]').fill('tutor@example.test'); await form.locator('[name="guardianConsent"]').check()
        await form.getByRole('button', { name: 'Continuar', exact: true }).click()
      }
      check(await form.getByRole('group', { name: 'Nombre visible en la comunidad', exact: true }).count() === 1, `Registro ${minor ? 'menor pasa por tutor' : 'adulto omite tutor'} y llega al perfil`)
      if (minor) check(await form.locator('[name="visibility"][value="comunidad"]').isDisabled(), 'Menor conserva perfil privado')
      await form.getByRole('button', { name: 'Continuar', exact: true }).click()
      await form.locator('[name="acceptRules"]').check(); await form.locator('[name="acceptPrivacy"]').check(); await form.getByRole('button', { name: 'Enviar solicitud', exact: true }).click()
      check(await page.getByRole('heading', { name: '¡Solicitud enviada!', exact: true }).count() === 1 && await page.getByText(/no se creó una cuenta real/).isVisible(), 'Solicitud pendiente identifica simulación')
    }
    await register(false)
    await page.getByRole('link', { name: 'Continuar al acceso demo', exact: true }).click()
    check(new URL(page.url()).pathname === '/login', 'Registro → Login conserva el recorrido completo de demostración')
    await page.getByRole('button', { name: /^Demo estudiante/ }).click()
    await page.locator('#community-demo-controls summary').click(); await link('/admin').click(); await adminGo('/admin/solicitudes')
    await page.getByRole('button', { name: 'Aprobar a Integracion Prueba', exact: true }).click()
    await adminGo('/admin/alumnos')
    check(await page.getByRole('row').filter({ has: page.getByRole('button', { name: 'Ficha de Integracion Prueba', exact: true }) }).filter({ hasText: 'Nuevo' }).count() === 1, 'Registro → aprobación → directorio conectado')
    await page.getByRole('button', { name: 'Ficha de Integracion Prueba', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Suspender acceso', exact: true }).click()
    check(await page.getByRole('dialog').getByRole('button', { name: 'Reactivar acceso', exact: true }).count() === 1, 'Suspensión demo actualiza la ficha')
    await page.getByRole('dialog').getByRole('button', { name: 'Reactivar acceso', exact: true }).click()
    check(await page.getByRole('dialog').getByRole('button', { name: 'Suspender acceso', exact: true }).count() === 1, 'Reactivación demo restaura la ficha')
    await page.keyboard.press('Escape'); await adminGo('/admin/configuracion')
    const comments = page.getByRole('switch', { name: 'Permitir comentarios', exact: true })
    await comments.click()
    check(await comments.getAttribute('aria-checked') === 'true' && await page.getByText('💬 Comentar', { exact: true }).count() === 1, 'Configuración actualiza su vista previa')
    const mandatory = page.getByRole('switch', { name: 'Exigir autorización del tutor', exact: true })
    await mandatory.press('Enter')
    check(await mandatory.getAttribute('aria-checked') === 'true', 'Regla obligatoria no se desactiva con teclado')
    if (await page.getByRole('button', { name: 'Abrir menú', exact: true }).isVisible()) await page.getByRole('button', { name: 'Abrir menú', exact: true }).click()
    await link('/login').click(); await page.getByRole('link', { name: 'Solicita tu acceso', exact: true }).click(); await register(true)
    await page.getByRole('link', { name: 'Ver la solicitud en el panel (demo)', exact: true }).click()
    check(await page.getByRole('button', { name: /Aprobar a Menor Prueba/ }).isDisabled(), 'Panel impide aprobar menor sin confirmación de tutor')
    const minorRow = page.getByRole('row').filter({ hasText: 'Menor Prueba' })
    await minorRow.getByRole('button', { name: 'Detalle de Menor Prueba', exact: true }).click()
    const requestDialog = page.getByRole('dialog')
    await requestDialog.getByRole('button', { name: 'Registrar autorización recibida (simulado)', exact: true }).click()
    await requestDialog.getByRole('button', { name: 'Aprobar a Menor Prueba', exact: true }).click()
    check(await page.getByRole('dialog').count() === 0, 'Confirmación simulada permite aprobar menor')
    for (const width of [1440, 768, 375, 320]) {
      await page.setViewportSize({ width, height: width > 375 ? 1000 : 812 })
      for (const route of ['/', '/login', '/registro', '/community', '/admin', '/admin/solicitudes', '/admin/publicaciones', '/admin/alumnos', '/admin/configuracion']) {
        await page.goto(`${baseURL}${route}`); await page.evaluate(() => document.fonts.ready)
        const row = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth, headings: document.querySelectorAll('h1').length, main: document.querySelectorAll('main').length }))
        matrix.push({ width, route, ...row }); check(!row.overflow && row.headings === 1 && row.main === 1, `${route} a ${width}: sin overflow ni pantalla vacía, un main y un H1`)
        if (width === 375 && route === '/login') await snap('03-login-375')
        if (width === 320 && route === '/admin') await snap('07-admin-320')
      }
    }
    await page.goto(`${baseURL}/login`); await page.getByRole('button', { name: /^Demo estudiante/ }).click()
    check(new URL(page.url()).pathname === '/community', 'Demo estudiante accesible sin credenciales')
    check(!requests.some((r) => !['GET', 'HEAD'].includes(r.method)) && !requests.some((r) => /SOLO-DEMO-642|RegistroDemo642|integracion%40example/.test(r.url + (r.body ?? ''))), 'Recorrido no envía credenciales ni escrituras de red')
    check(!errors.length && !warnings.length, `Sin errores ni advertencias de consola: ${JSON.stringify({ errors, warnings })}`)
    return { status: 'correcto', checks: details.length, details, matrix, errors, warnings, requestMethods: [...new Set(requests.map((r) => r.method))], initialStorageKeys: Object.keys(beforeStorage.local) }
  } finally { page.off('pageerror', onError); page.off('console', onConsole); page.off('request', onRequest) }
}
